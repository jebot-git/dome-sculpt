#!/usr/bin/env python3
"""Offline CC0 asset-to-C++ conversion. Not installed or used by the runtime.

Run from any directory; downloads only pinned, SHA256-verified files from the
committed assets/humanoid/SOURCES.json and writes src/humanoid-base.inc. No
MakeHuman program logic is imported or executed. Python code here is original.
"""
# SPDX-License-Identifier: GPL-3.0-or-later
import collections
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = json.loads((ROOT / 'assets/humanoid/SOURCES.json').read_text())
CACHE = ROOT / 'artifacts/humanoid-reference'
CACHE.mkdir(parents=True, exist_ok=True)
for item in MANIFEST['assets']:
    file = CACHE / Path(item['path']).name
    if not file.exists():
        url = ('https://raw.githubusercontent.com/makehumancommunity/makehuman/'
               + MANIFEST['commit'] + '/' + item['path'])
        file.write_bytes(urllib.request.urlopen(url).read())
    if hashlib.sha256(file.read_bytes()).hexdigest() != item['sha256']:
        raise ValueError('Asset hash mismatch: ' + item['path'])

positions, uvs = [], []
groups = collections.defaultdict(list)
group = ''
for line in (CACHE / 'base.obj').read_text().splitlines():
    words = line.split()
    if not words:
        continue
    if words[0] == 'v':
        positions.append(tuple(map(float, words[1:4])))
    elif words[0] == 'vt':
        uvs.append(tuple(map(float, words[1:3])))
    elif words[0] == 'g':
        group = words[1]
    elif words[0] == 'f':
        groups[group].append([tuple(int(i)-1 for i in x.split('/')[:2])
                              for x in words[1:]])

skeleton = json.loads((CACHE / 'default.mhskel').read_text())
weights = json.loads((CACHE / 'default_weights.mhw').read_text())
if skeleton['license'] != 'CC0' or weights['license'] != 'CC0':
    raise ValueError('Explicit per-asset CC0 grant missing')
bone_names = list(skeleton['bones'])
bone_indices = {name: index for index, name in enumerate(bone_names)}
raw_weights = collections.defaultdict(list)
for name, entries in weights['weights'].items():
    for vertex, weight in entries:
        if weight > 0:
            raw_weights[vertex].append((bone_indices[name], weight))

render_vertices, triangles, corners = [], [], {}
for face in groups['body']:
    if len(face) not in [3, 4]:
        raise ValueError('Unexpected body face size')
    indices = []
    for vertex, uv in face:
        key = (vertex, uv)
        if key not in corners:
            corners[key] = len(render_vertices)
            render_vertices.append((vertex, *uvs[uv]))
        indices.append(corners[key])
    triangles.extend(indices[:3])
    if len(indices) == 4:
        triangles.extend([indices[0], indices[2], indices[3]])

joint_vertices, bones = [], []
for name, bone in skeleton['bones'].items():
    segments = []
    for endpoint in ['head', 'tail']:
        vertices = skeleton['joints'][bone[endpoint]]
        segments.extend([len(joint_vertices), len(vertices)])
        joint_vertices.extend(vertices)
    bones.append((name, bone_indices.get(bone['parent'], -1), *segments))

weight_entries, weight_spans = [], []
for vertex in range(len(positions)):
    w = raw_weights[vertex]
    weight_spans.append((len(weight_entries), len(w)))
    weight_entries.extend(w)
for vertex, _, _ in render_vertices:
    if not raw_weights[vertex]:
        raise ValueError('Unweighted body vertex')

deltas, targets = [], []
for asset in MANIFEST['assets']:
    path = asset['path']
    if not path.endswith('.target'):
        continue
    entries = []
    data = (CACHE / Path(path).name).read_text()
    if 'released as CC0' not in data:
        raise ValueError('Explicit target CC0 grant missing: ' + path)
    for line in data.splitlines():
        if line.startswith('#') or not line.strip():
            continue
        words = line.split()
        entries.append((int(words[0]), *map(float, words[1:4])))
    targets.append((Path(path).stem, len(deltas), len(entries)))
    deltas.extend(entries)

def f(value):
    text = format(value, '.9g')
    return text + ('f' if '.' in text or 'e' in text else '.0f')

def vec(values):
    return '{' + ','.join(f(v) for v in values) + '}'

output = [
    '// SPDX-License-Identifier: CC0-1.0',
    '// Generated by tools/prepare-humanoid-assets.py; do not edit manually.',
    '// Asset credits: Data Collection AB, Joel Palmius, Jonas Hauquier;',
    '// original target credits include Manuel Bastioni. See assets/humanoid/.',
    '// Pinned MakeHuman revision: ' + MANIFEST['commit'],
    'static constexpr Vec3 source_positions[] = {',
    *[vec(v) + ',' for v in positions], '};',
    'static constexpr SourceVertex source_vertices[] = {',
    *['{' + str(v) + ',' + vec((u, w)) + '},' for v, u, w in render_vertices],
    '};', 'static constexpr uint32_t source_triangles[] = {',
    *[','.join(map(str, triangles[i:i+24])) + ',' for i in range(0, len(triangles), 24)],
    '};', 'static constexpr SourceBone source_bones[] = {',
    *['{' + json.dumps(b[0]) + ',' + ','.join(map(str, b[1:])) + '},' for b in bones],
    '};', 'static constexpr uint32_t source_joint_vertices[] = {',
    ','.join(map(str, joint_vertices)), '};',
    'static constexpr Influence source_weights[] = {',
    *['{' + str(j) + ',' + f(w) + '},' for j, w in weight_entries],
    '};', 'static constexpr SourceSpan source_weight_spans[] = {',
    *['{' + str(s) + ',' + str(n) + '},' for s, n in weight_spans], '};',
    'static constexpr SourceDelta source_deltas[] = {',
    *['{' + str(v) + ',' + vec((x, y, z)) + '},' for v, x, y, z in deltas], '};',
    'static constexpr SourceTarget source_targets[] = {',
    *['{' + json.dumps(n) + ',' + str(s) + ',' + str(c) + '},' for n, s, c in targets], '};'
]
for side in ['l', 'r']:
    vertices = sorted({v for face in groups['helper-' + side + '-eye'] for v, _ in face})
    output.extend(['static constexpr uint32_t source_' + side + '_eye[] = {',
                   ','.join(map(str, vertices)), '};'])
(ROOT / 'src/humanoid-base.inc').write_text('\n'.join(output) + '\n')
print('Generated body render vertices:', len(render_vertices),
      'triangles:', len(triangles)//3, 'bones:', len(bones),
      'target assets:', len(targets))

notices = ['MakeHuman CC0 asset grant and original credit evidence',
           'Revision: ' + MANIFEST['commit'],
           'Source paths and SHA256 hashes: SOURCES.json',
           'No AGPL program implementation is incorporated.', '']
for item in MANIFEST['assets']:
    name = Path(item['path']).name
    if name.endswith(('.obj', '.target')):
        header = []
        for line in (CACHE / name).read_text().splitlines():
            if line.startswith('#'):
                header.append(line)
            elif line.strip():
                break
        if not any('released as CC0' in line for line in header):
            raise ValueError('Missing explicit CC0 asset grant: ' + name)
        notices.extend([item['path'], *header, ''])
    elif name.endswith(('.mhskel', '.mhw')):
        metadata = json.loads((CACHE / name).read_text())
        notices.extend([item['path'], 'Copyright: ' + metadata['copyright'],
                        'License: ' + metadata['license'],
                        'Description: ' + metadata['description'], ''])
(ROOT / 'assets/humanoid/ASSET-NOTICES.txt').write_text('\n'.join(notices)+'\n')
for source, destination in [('LICENSE.md', 'MAKEHUMAN-LICENSE.txt'),
                             ('LICENSE.ASSETS.md', 'CC0-1.0.txt')]:
    (ROOT / 'assets/humanoid' / destination).write_bytes((CACHE/source).read_bytes())
