#!/usr/bin/env python3
"""Reproduce the integer-only nearest-even SoftFloat subset for device kernels."""
from pathlib import Path
import json
import hashlib
import re

root = Path(__file__).resolve().parents[1]
directory = root / 'third_party/softfloat'
record = json.loads((directory / 'SOURCES.json').read_text())
sources = []
prototypes = []
tables = []
for name in record['source_files']:
    raw = (directory / 'source' / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != record['source_files'][name]:
        raise RuntimeError(f'Pinned upstream source changed: {name}')
    text = raw.decode()
    text = re.sub(r'^#include[^\n]*\n', '', text, flags=re.M)
    # Avoid C union type-punning when compiled as C++/SYCL. Every value is an
    # opaque integer word: these substitutions perform no floating operation.
    text = text.replace('union ui64_f64', 'float64_t')
    text = re.sub(r'\b(u[A-Z])\.ui\b', r'\1.v', text)
    text = re.sub(r'\b(u[A-Z])\.f\b', r'\1', text)
    text = text.replace('softfloat_exceptionFlags |= softfloat_flag_inexact;',
                        '/* Numeric-only API: floating exception flags are not exposed. */')
    if name == 's_approxRecip_1Ks.c':
        # CUDA/HIP device code cannot dynamically index a host constexpr array.
        # Emit the same pinned constants as host/device switch accessors, letting
        # each compiler place its own lookup representation in device storage.
        def table_function(match):
            values = [v.strip() for v in match.group(2).split(',') if v.strip()]
            if len(values) != 16:
                raise RuntimeError('Unexpected reciprocal table size')
            cases = ''.join(f'case {i}: return {v};\n' for i, v in enumerate(values))
            return ('DOME_SF_FN uint16_t ' + match.group(1) +
                    '(unsigned index) { switch(index) {\n' + cases +
                    'default: return 0;\n} }')
        text, count = re.subn(r'const uint16_t (\w+)\[16\]\s*=\s*\{([^}]+)\};',
                              table_function, text, flags=re.S)
        if count != 2:
            raise RuntimeError('Missing pinned reciprocal tables')
        tables.append(text)
        continue
    text = re.sub(r'extern const uint16_t softfloat_approxRecip_1k[01]s\[16\];', '', text)
    text = re.sub(r'(softfloat_approxRecip_1k[01]s)\[index\]', r'\1(index)', text)
    plain = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    match = re.search(r'((?:struct\s+)?\w+)\s+(\w+)\s*\(([^;{}]*)\)\s*\{', plain)
    if not match:
        raise RuntimeError(f'Missing source function definition: {name}')
    signature = match.group(0)[:-1].strip()
    prototypes.append('DOME_SF_FN ' + signature + ';')
    # The declaration can be split over two lines in upstream C.
    pattern = re.escape(match.group(1)) + r'\s+' + re.escape(match.group(2)) + r'\s*\('
    text, count = re.subn(pattern, 'DOME_SF_FN ' + match.group(1) + ' ' + match.group(2) + '(', text, count=1)
    if count != 1:
        raise RuntimeError(f'Cannot annotate source function: {name}')
    sources.append(text)

prefix = r'''// Generated by tools/generate-softfloat-f64.py; do not edit by hand.
// Original source/notice preserved below; see COPYING.txt and SOURCES.json.
#pragma once
#include <cstdint>
#if defined(__CUDACC__) || defined(__HIPCC__)
#define DOME_SF_FN __host__ __device__ inline
#else
#define DOME_SF_FN inline
#endif
#define SOFTFLOAT_FAST_INT64
#define INLINE_LEVEL 5
namespace dome::softfloat64 {
struct float64_t { uint64_t v; };
struct uint128 { uint64_t v0, v64; };
struct exp16_sig64 { int_fast16_t exp; uint_fast64_t sig; };
inline constexpr uint_fast8_t softfloat_round_near_even=0, softfloat_round_min=2,
  softfloat_round_max=3, softfloat_round_near_maxMag=4, softfloat_round_odd=6,
  softfloat_tininess_beforeRounding=0, softfloat_roundingMode=0,
  softfloat_detectTininess=1, softfloat_flag_inexact=1,
  softfloat_flag_underflow=2, softfloat_flag_overflow=4,
  softfloat_flag_infinite=8, softfloat_flag_invalid=16;
DOME_SF_FN void softfloat_raiseFlags(uint_fast8_t) {}
DOME_SF_FN uint_fast8_t softfloat_countLeadingZeros32(uint32_t a) {
  if(!a)return 32;uint_fast8_t n=0;while(!(a&0x80000000U)){a<<=1;++n;}return n;
}
DOME_SF_FN uint_fast8_t softfloat_countLeadingZeros64(uint64_t a) {
  if(!a)return 64;uint_fast8_t n=0;while(!(a&UINT64_C(0x8000000000000000))){a<<=1;++n;}return n;
}
DOME_SF_FN bool softfloat_isSigNaNF64UI(uint_fast64_t a) {
  return (a&UINT64_C(0x7FF8000000000000))==UINT64_C(0x7FF0000000000000) && (a&UINT64_C(0x0007FFFFFFFFFFFF));
}
#define signF64UI(a) (bool(uint64_t(a)>>63))
#define expF64UI(a) (int_fast16_t((uint64_t(a)>>52)&0x7FF))
#define fracF64UI(a) (uint64_t(a)&UINT64_C(0x000FFFFFFFFFFFFF))
#define packToF64UI(sign,exp,sig) ((uint64_t(bool(sign))<<63)+(uint64_t(exp)<<52)+uint64_t(sig))
#define defaultNaNF64UI UINT64_C(0xFFF8000000000000)
#define isNaNF64UI(a) ((uint64_t(a)&UINT64_C(0x7FF0000000000000))==UINT64_C(0x7FF0000000000000) && fracF64UI(a))
'''
suffix = r'''
} // namespace dome::softfloat64
#undef signF64UI
#undef expF64UI
#undef fracF64UI
#undef packToF64UI
#undef defaultNaNF64UI
#undef isNaNF64UI
#undef SOFTFLOAT_FAST_INT64
#undef INLINE_LEVEL
#undef DOME_SF_FN
'''
output = prefix + '\n'.join(prototypes) + '\n' + '\n'.join(tables + sources) + suffix
(directory / 'dome_f64.hpp').write_text(output)
